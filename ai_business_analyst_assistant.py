def create_ba_prompt(requirement):

    prompt = f"""
You are an experienced Business Analyst working on a hotel management software platform.

Analyze the following business requirement:

BUSINESS REQUIREMENT:
{requirement}

Provide the analysis in the following structure:

1. REQUIREMENT SUMMARY
Give a short and clear summary of the requirement.

2. FUNCTIONAL REQUIREMENTS
Convert the business requirement into clear functional requirements.
List them as numbered points.

3. USER STORY
Create one Agile user story using this format:

As a [user],
I want [functionality],
so that [business benefit].

4. ACCEPTANCE CRITERIA
Create 3 to 5 acceptance criteria using Given / When / Then format.

5. TEST SCENARIOS
Create 3 to 5 basic test scenarios.

6. ASSUMPTIONS
Mention any assumptions or missing information that
may require clarification from the business stakeholder.

IMPORTANT:
- Do not invent information that is not present in the requirement.
- Clearly mention assumptions when information is missing.
- Use professional Business Analyst terminology.
- Keep the response structured and concise.
- Focus on business requirements rather than technical implementation.
"""

    return prompt

